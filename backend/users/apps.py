from django.apps import AppConfig


class UsersConfig(AppConfig):
    """
    Конфигурация приложения для работы с кастомной моделью пользователей.

    Определяет базовые параметры приложения:
    - Тип авто-поля для моделей (BigAutoField)
    - Системное имя приложения (users)
    - Человекочитаемое название для админ-панели
    """

    # Использование BigAutoField в качестве первичного ключа по умолчанию
    default_auto_field = 'django.db.models.BigAutoField'

    # Имя приложения (должно соответствовать имени пакета)
    name = 'users'

    # Отображаемое имя в интерфейсе администратора
    verbose_name = 'Кастомные пользователи'
