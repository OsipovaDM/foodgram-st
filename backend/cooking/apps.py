from django.apps import AppConfig


class CookingConfig(AppConfig):
    """
    Конфигурация приложения 'cooking' (Фудграм).

    Определяет базовые параметры приложения:
    - Тип авто-поля для моделей
    - Имя приложения
    - Человеко-читаемое название для админ-панели
    """

    # Тип автоматического поля для первичных ключей моделей
    default_auto_field = 'django.db.models.BigAutoField'

    # Имя приложения (должно соответствовать имени папки приложения)
    name = 'cooking'

    # Отображаемое имя в админ-панели
    verbose_name = 'Фудграм'
